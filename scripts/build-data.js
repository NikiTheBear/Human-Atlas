/* ============================================================
   build-data.js — 将 src/data 下的 JSON 编译为 ES 模块 bundle
   使 UI 层只依赖 import，不依赖 fetch（兼容 file:// 与静态托管）
   ============================================================ */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const DATA_DIR = path.join(ROOT, 'src', 'data');

const read = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));

const dimensions = read(path.join(DATA_DIR, 'dimensions.json'));

/* ---------- volumes ---------- */
const volDir = path.join(DATA_DIR, 'volumes');
const volumes = {};
const volFiles = fs.readdirSync(volDir).filter((f) => /^vol\d+\.json$/.test(f)).sort();
for (const f of volFiles) {
  const v = read(path.join(volDir, f));
  volumes[v.volume_id] = v;
}

/* ---------- mirrors: 支持拆分碎片后合并 ---------- */
const mirrorDir = path.join(DATA_DIR, 'mirrors');
let mirrors = {};
const fragments = fs.existsSync(mirrorDir)
  ? fs.readdirSync(mirrorDir).filter((f) => f.endsWith('.json')).sort()
  : [];

for (const f of fragments) {
  const frag = read(path.join(mirrorDir, f));
  mirrors = { ...mirrors, ...frag };
}
const singleMirror = path.join(DATA_DIR, 'mirrors.json');
if (fs.existsSync(singleMirror)) {
  mirrors = { ...mirrors, ...read(singleMirror) };
}

// 同时输出一份合并后的 mirrors.json，使目录结构与规范一致
// （fragments 仍是可编辑的唯一来源，此文件为自动生成产物）
fs.writeFileSync(
  singleMirror,
  `${JSON.stringify(mirrors, null, 2)}\n`,
  'utf8',
);

/* ---------- express: 28 题极速精选（只存 id 引用，不复制题干） ---------- */
const expressPath = path.join(DATA_DIR, 'express.json');
const express = fs.existsSync(expressPath) ? read(expressPath) : { questions: [] };

/* ---------- archetypes / cross rules ---------- */
const archetypes = read(path.join(DATA_DIR, 'archetypes.json'));
const crossRules = read(path.join(DATA_DIR, 'cross_rules.json'));
const pairRules = fs.existsSync(path.join(DATA_DIR, 'pair_rules.json'))
  ? read(path.join(DATA_DIR, 'pair_rules.json'))
  : { resonance: [], collisions: [], compass: [] };

/* ---------- emit ---------- */
const header = `/* AUTO-GENERATED by scripts/build-data.js — DO NOT EDIT BY HAND */
`;

const out = `${header}
export const DIMENSIONS = ${JSON.stringify(dimensions, null, 2)};

export const VOLUMES = ${JSON.stringify(volumes, null, 2)};

export const MIRRORS = ${JSON.stringify(mirrors, null, 2)};

export const ARCHETYPES = ${JSON.stringify(archetypes, null, 2)};

export const CROSS_RULES = ${JSON.stringify(crossRules, null, 2)};

export const PAIR_RULES = ${JSON.stringify(pairRules, null, 2)};

export const EXPRESS = ${JSON.stringify(express, null, 2)};

export const DIM_ORDER = DIMENSIONS.dims.map((d) => d.id);
export const DIM_MAP = Object.fromEntries(DIMENSIONS.dims.map((d) => [d.id, d]));
`;

fs.writeFileSync(path.join(DATA_DIR, 'bundle.js'), out, 'utf8');

/* ---------- 紧凑版：供单文件构建使用（无缩进，约省 54% 体积） ---------- */
const compact = `${header}
export const DIMENSIONS = ${JSON.stringify(dimensions)};

export const VOLUMES = ${JSON.stringify(volumes)};

export const MIRRORS = ${JSON.stringify(mirrors)};

export const ARCHETYPES = ${JSON.stringify(archetypes)};

export const CROSS_RULES = ${JSON.stringify(crossRules)};

export const PAIR_RULES = ${JSON.stringify(pairRules)};

export const EXPRESS = ${JSON.stringify(express)};

export const DIM_ORDER = DIMENSIONS.dims.map((d) => d.id);
export const DIM_MAP = Object.fromEntries(DIMENSIONS.dims.map((d) => [d.id, d]));
`;
fs.writeFileSync(path.join(DATA_DIR, 'bundle.compact.js'), compact, 'utf8');

/* ---------- 去 AI 腔黑名单校验 ---------- */
const BLACKLIST = [
  '林舟', '沈明', '陆言',
  '留一层备份', '把牌摊开', '在心里划掉', '把桥烧掉', '后背是温的', '接住情绪',
];
const banned = [];
for (const [vid, vol] of Object.entries(volumes)) {
  const blob = JSON.stringify(vol);
  for (const w of BLACKLIST) {
    if (blob.includes(w)) banned.push(`${vid} → ${w}`);
  }
}
if (banned.length) {
  console.error('[data] ✗ 题库出现黑名单词汇（要求去 AI 腔）：');
  banned.forEach((b) => console.error('   ' + b));
  process.exitCode = 1;
} else {
  console.log('[data] ✓ 无黑名单词汇');
}

/* ---------- express 清单校验：id 必须存在、无重复 ---------- */
{
  const allIds = new Map();
  for (const [vid, vol] of Object.entries(volumes)) {
    for (const q of vol.questions || []) allIds.set(q.id, vid);
  }
  const list = express.questions || [];
  const missing = list.filter((id) => !allIds.has(id));
  const dupes = list.filter((id, i) => list.indexOf(id) !== i);
  const slow = [];
  for (const id of list) {
    const vid = allIds.get(id);
    if (!vid) continue;
    const q = (volumes[vid].questions || []).find((x) => x.id === id);
    if (!q) continue;
    if (q.type !== 'forced_choice' && q.type !== 'impulse_3s') slow.push(id);
  }
  const problems = [];
  if (missing.length) problems.push(`不存在的 id：${missing.join(', ')}`);
  if (dupes.length) problems.push(`重复 id：${dupes.join(', ')}`);
  if (slow.length) problems.push(`极速模式只允许快答题型，这些是慢题：${slow.join(', ')}`);
  if (list.length !== 28) problems.push(`题量应为 28，实际 ${list.length}`);
  if (problems.length) {
    console.error('[data] ✗ express 清单有问题：');
    problems.forEach((p) => console.error('   ' + p));
    process.exitCode = 1;
  } else {
    console.log(`[data] ✓ express 清单 ${list.length} 题，全部为快答题型`);
  }
}

/* ---------- 筹码题配置校验：禁止负 gain / base 混用 ---------- */
const budgetIssues = [];
for (const [vid, vol] of Object.entries(volumes)) {
  for (const q of vol.questions || []) {
    if (q.type !== 'budget_100') continue;
    for (const it of q.items || []) {
      if (!it.dim) budgetIssues.push(`${vid}/${q.id}[${it.key}] → 缺少 dim`);
      if (Number(it.gain) < 0) {
        budgetIssues.push(`${vid}/${q.id}[${it.key}] → gain 为负（${it.gain}），请改用 reverse:true`);
      }
      if (it.base !== undefined && Number(it.base) !== 0) {
        budgetIssues.push(`${vid}/${q.id}[${it.key}] → base=${it.base}，规范要求 base:0`);
      }
    }
    const total = 0;
    void total;
  }
}
if (budgetIssues.length) {
  console.error('[data] ✗ 筹码题配置不规范（会导致区间倒置或计分压扁）：');
  budgetIssues.slice(0, 20).forEach((x) => console.error('   ' + x));
  process.exitCode = 1;
} else {
  console.log('[data] ✓ 筹码题配置规范（base:0 / gain:1，反向用 reverse）');
}

/* ---------- 题文一致性：context 与 prompt 不能指向不同场景 ---------- */
const CLASH = [
  ['电梯', ['无路可退', '逼到']],
  ['前同事在一家公司做了十年', ['第二天要交']],
];
const clashes = [];
for (const [vid, vol] of Object.entries(volumes)) {
  for (const q of vol.questions || []) {
    const ctx = q.context || '';
    const pr = q.prompt || '';
    for (const [needle, bads] of CLASH) {
      if (!ctx.includes(needle)) continue;
      for (const bad of bads) {
        if (pr.includes(bad)) clashes.push(`${vid}/${q.id} → context 含「${needle}」但 prompt 含「${bad}」`);
      }
    }
    // 语言噪声：连续重复汉字（只查题干与情境，排除「做不了了」这类自然口语）
    if (/(先先|再再|的的|是是|在在|都都)/.test(pr + ctx)) {
      clashes.push(`${vid}/${q.id} → 出现重复字（先先/再再/的的…）`);
    }
  }
}
if (clashes.length) {
  console.error('[data] ✗ 题文一致性校验失败：');
  clashes.slice(0, 20).forEach((x) => console.error('   ' + x));
  process.exitCode = 1;
} else {
  console.log('[data] ✓ 题文一致，无重复字');
}

/* ---------- 野字段校验：任何 effects 键必须属于注册表 ---------- */
const validDims = new Set(dimensions.dims.map((d) => d.id));
const wildFields = [];
for (const [vid, vol] of Object.entries(volumes)) {
  for (const q of vol.questions || []) {
    const check = (obj, where) => {
      for (const k of Object.keys(obj || {})) {
        if (!validDims.has(k)) wildFields.push(`${vid}/${q.id}${where} → ${k}`);
      }
    };
    check(q.effects, '');
    for (const o of q.options || []) check(o.effects, `[${o.key}]`);
    for (const it of q.items || []) {
      if (it.dim && !validDims.has(it.dim)) wildFields.push(`${vid}/${q.id}[${it.key}].dim → ${it.dim}`);
      check(it.effects, `[${it.key}]`);
    }
    for (const v of q.values || []) check(v.effects, `[${v.key}]`);
  }
}
if (wildFields.length) {
  console.error('[data] ✗ 发现野维度键（必须修复，否则该维度贡献会被丢弃）：');
  wildFields.slice(0, 20).forEach((w) => console.error('   ' + w));
  if (wildFields.length > 20) console.error(`   … 共 ${wildFields.length} 处`);
  process.exitCode = 1;
} else {
  console.log('[data] ✓ 维度键全部合法');
}

const qTotal = Object.values(volumes).reduce((a, v) => a + (v.questions?.length || 0), 0);
const dimTotal = Object.keys(mirrors).length;
const missMirror = dimensions.dims.filter((d) => !mirrors[d.id]).map((d) => d.id);

console.log(
  `[data] volumes=${volFiles.length} questions=${qTotal} mirrors=${dimTotal}/${dimensions.dims.length} archetypes=${archetypes.archetypes?.length ?? 0} crossRules=${crossRules.length} express=${(express.questions || []).length}`,
);
console.log(
  `[data] bundle.js ${(out.length / 1024).toFixed(0)}K · bundle.compact.js ${(compact.length / 1024).toFixed(0)}K`,
);
if (missMirror.length) console.log(`[data] 缺少双面镜文案：${missMirror.join(', ')}`);
